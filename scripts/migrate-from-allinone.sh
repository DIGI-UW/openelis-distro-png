#!/usr/bin/env bash
# Move a site from an openelis-docker ("allinone") folder to this distro.
#
#   sudo ./scripts/migrate-from-allinone.sh prepare  <allinone-dir>
#       Safe while the old stack runs. Writes this distro's .env from the old
#       one, generates the Bridge pairing code and new internal-TLS passwords,
#       keeps the database encryption key, picks up the host's Let's Encrypt
#       certificate, pulls the images and validates the compose files.
#
#   sudo ./scripts/migrate-from-allinone.sh cutover  <allinone-dir>
#       Takes a database dump and a Bridge-state archive, stops the old stack
#       (`docker compose down`, volumes kept), and copies the database, Bridge
#       state, uploads and search index into DATA_ROOT with their owners.
#       Does not start anything: run `docker compose up -d` afterwards.
#
#   sudo ./scripts/migrate-from-allinone.sh rollback <allinone-dir>
#       Stops this stack and starts the old one again. The old folder is never
#       modified, so this returns to the state at cutover time; anything entered
#       on this stack since then is not carried back.
#
# See docs/migrating-from-allinone.md for the full runbook.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

usage() { sed -n '2,21p' "$0" | sed 's/^# \{0,1\}//'; exit 2; }
die() { echo "ERROR: $*" >&2; exit 1; }
log() { echo "[migrate] $*"; }

CMD="${1:-}"; OLD="${2:-}"
[ -n "$CMD" ] && [ -n "$OLD" ] || usage
OLD="$(cd "$OLD" 2>/dev/null && pwd)" || die "no such directory: $2"
[ -f "$OLD/docker-compose.yml" ] && [ -d "$OLD/configs" ] || die "$OLD does not look like an openelis-docker folder"
[ "$(id -u)" -eq 0 ] || die "run as root: sudo $0 $*"
OWNER="${SUDO_USER:-root}"

# Read KEY from an env file: last assignment wins, surrounding spaces and quotes removed.
env_get() {
    local file="$1" key="$2"
    [ -f "$file" ] || return 0
    grep -E "^[[:space:]]*${key}=" "$file" | tail -n1 | cut -d= -f2- \
        | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//; s/^"(.*)"$/\1/; s/^'"'"'(.*)'"'"'$/\1/'
}

data_root() {
    local d; d="$(env_get .env DATA_ROOT)"; d="${d:-./data}"
    case "$d" in /*) echo "$d";; *) echo "$ROOT/${d#./}";; esac
}

prepare() {
    local old_env="$OLD/.env" stamp
    [ -f "$old_env" ] || die "$old_env not found"
    stamp="$(date -u +%Y%m%dT%H%M%SZ)"

    # The key OpenELIS encrypted database secrets with on the old stack.
    local enc_line enc
    enc_line="$(grep -E '^[[:space:]]*encryption\.general\.password[[:space:]]*=' "$OLD/configs/properties/common.properties" | tail -n1 | cut -d= -f2- | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//')"
    case "$enc_line" in
        '${SSL_KEYSTORE_PASSWORD}') enc="$(env_get "$old_env" SSL_KEYSTORE_PASSWORD)" ;;
        '${OE_ENCRYPTION_PASSWORD}') enc="$(env_get "$old_env" OE_ENCRYPTION_PASSWORD)" ;;
        '${'*) die "unrecognised encryption.general.password placeholder: $enc_line" ;;
        *) enc="$enc_line" ;;
    esac
    [ -n "$enc" ] || die "could not determine the database encryption key from $OLD"

    local db_pw admin_pw oe_admin_pw
    db_pw="$(env_get "$old_env" OE_DB_PASSWORD)"
    admin_pw="$(env_get "$old_env" ADMIN_PASSWORD)"
    oe_admin_pw="$(env_get "$old_env" OE_ADMIN_PASSWORD)"
    [ -n "$db_pw" ] || die "OE_DB_PASSWORD missing from $old_env"

    # Let's Encrypt: a certbot on the host owns the certificate if exactly one
    # lineage exists under /etc/letsencrypt/live.
    local lineages cert_name="" le_email
    lineages="$(find /etc/letsencrypt/live -mindepth 1 -maxdepth 1 -type d -printf '%f\n' 2>/dev/null || true)"
    if [ -n "$lineages" ] && [ "$(echo "$lineages" | wc -l)" -eq 1 ]; then
        cert_name="$lineages"
    fi
    le_email="$(env_get .env LETSENCRYPT_EMAIL)"

    local compose_file="docker-compose.yml:docker-compose.analyzers.yml"
    [ -n "$cert_name" ] && compose_file="${compose_file}:compose.letsencrypt.yaml"
    [ -f docker-compose.site.yml ] && compose_file="${compose_file}:docker-compose.site.yml"

    # Values generated by an earlier `prepare` are kept, so re-running it does
    # not rotate the pairing code or the internal TLS passwords.
    local pairing="" ks_pw="" ts_pw=""
    if [ -f .env ] && grep -q '^# Written by scripts/migrate-from-allinone.sh prepare' .env; then
        pairing="$(env_get .env ANALYZER_BRIDGE_PAIRING_CODE)"
        ks_pw="$(env_get .env SSL_KEYSTORE_PASSWORD)"
        ts_pw="$(env_get .env SSL_TRUSTSTORE_PASSWORD)"
    fi
    pairing="${pairing:-$(openssl rand -hex 16)}"
    ks_pw="${ks_pw:-$(openssl rand -hex 16)}"
    ts_pw="${ts_pw:-$(openssl rand -hex 16)}"

    if [ -f .env ]; then
        install -m 0600 -o "$OWNER" .env ".env.pre-migration-${stamp}"
        log "kept the previous .env as .env.pre-migration-${stamp}"
    fi

    # Recreate the file so it is 0600 even if an older .env was world-readable.
    rm -f .env
    umask 077
    {
        echo "# Written by scripts/migrate-from-allinone.sh prepare (${stamp}) from $OLD/.env"
        echo "COMPOSE_FILE=${compose_file}"
        echo "DATA_ROOT=./data"
        echo
        echo "OE_DB_PASSWORD=${db_pw}"
        echo "ADMIN_PASSWORD=${admin_pw}"
        echo "OE_ADMIN_PASSWORD=${oe_admin_pw}"
        echo "# The key the existing database's secrets are encrypted with. Never change it."
        echo "OE_ENCRYPTION_PASSWORD=${enc}"
        echo
        echo "# The copied database is paired with the old Bridge: after the first start,"
        echo "# enter this code on Admin > Analyzers to pair OpenELIS with this stack's Bridge."
        echo "ANALYZER_BRIDGE_PAIRING_CODE=${pairing}"
        echo "ANALYZER_ASTM_PORT=12000"
        echo "# TRACE as on the old stack, to follow ASTM framing; INFO once analyzers are settled."
        echo "BRIDGE_LOG_LEVEL=TRACE"
        echo "ANALYZER_HOST_MOUNT=./configs/analyzer-drops"
        echo
        echo "TZ=Pacific/Port_Moresby"
        echo "# The catalog lives in the copied database; don't import the baseline over it."
        echo "OE_CONFIGURATION_AUTOCREATE=false"
        echo "LOCAL_BIND=127.0.0.1"
        echo
        echo "# This stack's own internal TLS stores (generated on first start)."
        echo "SSL_TRUSTSTORE_PATH=/etc/openelis-global/truststore"
        echo "SSL_TRUSTSTORE_PASSWORD=${ts_pw}"
        echo "SSL_KEYSTORE_PATH=/etc/openelis-global/keystore"
        echo "SSL_KEYSTORE_PASSWORD=${ks_pw}"
        if [ -n "$cert_name" ]; then
            echo
            echo "# Let's Encrypt certificate managed by the host's certbot."
            echo "LETSENCRYPT_EMAIL=${le_email}"
            echo "LETSENCRYPT_DOMAINS=${cert_name}"
            echo "LETSENCRYPT_PRIMARY_DOMAIN=${cert_name}"
            echo "LETSENCRYPT_CERT_NAME=${cert_name}"
            echo "LETSENCRYPT_DIR=/etc/letsencrypt"
            echo "CERTBOT_WEBROOT=/var/www/certbot"
        fi
    } > .env
    chown "$OWNER" .env
    log "wrote .env (mode 0600). Let's Encrypt lineage: ${cert_name:-none found, self-signed}"

    docker compose config -q || die "docker compose config failed"
    log "compose files validate: ${compose_file}"
    log "pulling images (the running stack is not touched)..."
    docker compose pull --quiet
    log "prepare done. Nothing was started or stopped."
}

cutover() {
    [ -f .env ] || die "no .env: run '$0 prepare $OLD' first"
    local data stamp dest old_db old_bridge
    data="$(data_root)"
    stamp="$(date -u +%Y%m%dT%H%M%SZ)"
    dest="$ROOT/backups/cutover-${stamp}"
    old_db="$OLD/configs/database/data"
    old_bridge="$OLD/configs/bridge-state"
    [ -d "$old_db" ] || die "$old_db not found"
    if [ -d "$data/db" ] && [ -n "$(ls -A "$data/db" 2>/dev/null)" ]; then
        die "$data/db is not empty; move it aside before a cutover"
    fi

    mkdir -p "$dest"; chmod 0700 "$dest"
    if docker ps --format '{{.Names}}' | grep -qx openelisglobal-database; then
        log "dumping the database from the old stack..."
        docker exec openelisglobal-database pg_dump -U clinlims -d clinlims -Fc --no-owner --no-acl > "$dest/clinlims.dump"
        [ "$(stat -c %s "$dest/clinlims.dump")" -gt 1024 ] || die "database dump looks empty"
        log "  $(du -h "$dest/clinlims.dump" | cut -f1) $dest/clinlims.dump"
    else
        log "old database container is not running; skipping the dump (the data directory is still copied)"
    fi
    install -m 0600 "$OLD/.env" "$dest/allinone.env"

    log "stopping the old stack ($OLD)..."
    (cd "$OLD" && docker compose down)

    if [ -d "$old_bridge" ]; then
        tar --numeric-owner -C "$OLD/configs" -czf "$dest/allinone-bridge-state.tar.gz" bridge-state
    fi

    log "copying the database data directory..."
    mkdir -p "$data/db"
    cp -a "$old_db/." "$data/db/"
    if [ -d "$old_bridge" ]; then
        log "copying the Analyzer Bridge state..."
        mkdir -p "$data/bridge"
        cp -a "$old_bridge/." "$data/bridge/"
    fi
    local d
    for d in branding nce-attachments; do
        if [ -d "$OLD/configs/$d" ]; then
            mkdir -p "$data/webapp/$d"
            cp -a "$OLD/configs/$d/." "$data/webapp/$d/"
        fi
    done
    local project vol
    project="$(basename "$OLD")"
    vol="${project}_lucene_index-vol"
    if docker volume inspect "$vol" >/dev/null 2>&1; then
        log "copying the search index from volume $vol..."
        mkdir -p "$data/webapp/lucene"
        docker run --rm --entrypoint cp -v "$vol:/from:ro" -v "$data/webapp/lucene:/to" itechuw/certgen:main -a /from/. /to/
    fi

    log "copied:"
    du -sh "$data/db" "$data/bridge" 2>/dev/null | sed 's/^/  /'
    log "backups of the old stack: $dest"
    log "cutover done. Next: docker compose up -d  (see docs/migrating-from-allinone.md)"
}

rollback() {
    log "stopping this stack..."
    docker compose down
    log "starting the old stack ($OLD)..."
    (cd "$OLD" && docker compose up -d)
    log "rollback done. This stack's data is kept under $(data_root) for inspection."
}

case "$CMD" in
    prepare) prepare ;;
    cutover) cutover ;;
    rollback) rollback ;;
    *) usage ;;
esac
